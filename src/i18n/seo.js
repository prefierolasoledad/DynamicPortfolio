import { getDictionary } from "@/i18n";
import { htmlLang, locales } from "@/i18n/config";
import { BtnList } from "@/app/data";

// The main (canonical) address. Search engines are told this is the real
// home of every page, even when the same site is served from another host,
// so rankings aren't split between domains.
export const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL || "https://karanbhatt.me").replace(
  /\/$/,
  ""
);

// Hosts that have their own set of preview images (public/og/<host>/).
// Add a host here and to OG_HOSTS in scripts/generate-og.mjs to support it.
export const ogHosts = ["karanbhatt.me", "karan-bhatt-portfolio.netlify.app"];

// The address this particular build is deployed to, read from the variables
// each host sets during its build (Netlify: URL, Vercel:
// VERCEL_PROJECT_PRODUCTION_URL). Preview images are served from here, so a
// shared Netlify link shows the Netlify card and a karanbhatt.me link shows
// the karanbhatt.me card. Override with NEXT_PUBLIC_DEPLOY_URL.
const withProtocol = (host) => (host && !/^https?:\/\//.test(host) ? `https://${host}` : host);
export const deployUrl = (
  process.env.NEXT_PUBLIC_DEPLOY_URL ||
  (process.env.NETLIFY && process.env.URL) ||
  withProtocol(process.env.VERCEL_PROJECT_PRODUCTION_URL) ||
  siteUrl
).replace(/\/$/, "");

const deployHost = new URL(deployUrl).hostname;
const ogHost = ogHosts.includes(deployHost) ? deployHost : ogHosts[0];

export const pagePaths = { home: "", about: "/about", projects: "/projects", contact: "/contact" };

// Preview image per language for this host, generated by
// scripts/generate-og.mjs (relative; resolved against deployUrl).
export const ogImage = (lang) => `/og/${ogHost}/${lang}.png`;

const socialLinks = BtnList.filter((b) => b.newTab && b.link.startsWith("http")).map(
  (b) => b.link
);

// Full metadata for one page in one language: title, description, canonical
// URL, hreflang alternates, Open Graph and Twitter cards.
export function buildMetadata(lang, page) {
  const { seo } = getDictionary(lang);
  const { title, description } = seo.pages[page];
  const path = pagePaths[page];
  // Absolute, on the canonical domain, whichever host serves the page.
  const url = `${siteUrl}/${lang}${path}`;

  const languages = Object.fromEntries(
    locales.map((l) => [htmlLang[l], `${siteUrl}/${l}${path}`])
  );
  languages["x-default"] = `${siteUrl}/en${path}`;

  const image = {
    url: ogImage(lang),
    width: 1200,
    height: 630,
    alt: seo.ogImageAlt,
    type: "image/png",
  };

  return {
    title: page === "home" ? { absolute: title } : title,
    description,
    keywords: seo.keywords,
    alternates: { canonical: url, languages },
    openGraph: {
      type: page === "about" ? "profile" : "website",
      // The shared host's own address, so a Netlify link previews as Netlify.
      // (The canonical link above still sends search engines to siteUrl.)
      url: `${deployUrl}/${lang}${path}`,
      siteName: seo.siteName,
      title: page === "home" ? title : `${title} | ${seo.siteName}`,
      description,
      locale: seo.ogLocale,
      alternateLocale: locales
        .filter((l) => l !== lang)
        .map((l) => getDictionary(l).seo.ogLocale),
      images: [image],
      ...(page === "about" && {
        firstName: "Karan",
        lastName: "Bhatt",
        username: "prefierolasoledad",
      }),
    },
    twitter: {
      card: "summary_large_image",
      title: page === "home" ? title : `${title} | ${seo.siteName}`,
      description,
      images: [image],
    },
  };
}

// schema.org data so search engines understand who the site is about.
export function buildJsonLd(lang) {
  const { seo } = getDictionary(lang);
  const person = {
    "@type": "Person",
    "@id": `${siteUrl}/#person`,
    name: "Karan Bhatt",
    alternateName: ["करन भट्ट", "カラン・バット", "prefierolasoledad"],
    url: `${siteUrl}/${lang}`,
    image: `${deployUrl}${ogImage(lang)}`,
    jobTitle: seo.jobTitle,
    description: seo.personDescription,
    worksFor: { "@type": "Organization", name: "GSX Solutions" },
    alumniOf: {
      "@type": "CollegeOrUniversity",
      name: "University School of Automation and Robotics",
    },
    address: { "@type": "PostalAddress", addressLocality: "New Delhi", addressCountry: "IN" },
    knowsAbout: [
      "Node.js",
      "TypeScript",
      "PostgreSQL",
      "Redis",
      "Kafka",
      "Docker",
      "Kubernetes",
      "System Design",
      "Distributed Systems",
      "Natural Language Processing",
      "Machine Translation",
    ],
    knowsLanguage: ["en", "hi", "ja"],
    sameAs: socialLinks,
  };
  const website = {
    "@type": "WebSite",
    "@id": `${siteUrl}/#website`,
    url: siteUrl,
    name: seo.siteName,
    inLanguage: htmlLang[lang],
    author: { "@id": `${siteUrl}/#person` },
  };
  return { "@context": "https://schema.org", "@graph": [person, website] };
}
